#!/usr/bin/env python3
"""
parse_results.py -- turn the raw SST counter dumps into tables.

Inputs (copied verbatim from ckunda_proj2p2.tar.gz, memHierarchy/):
  results/miranda/miranda_bus_suite_<pattern>_<mesi|msi>.out   (14 files, Part 1)
  results/prospero/prospero_mesi_<base|opt>.out                (2 files,  Part 2)

Each .out has one "Counter[l1cacheN] inv=.. interv=.. getS_sent=.. getX_sent=..
getSX_sent=.. trans=.. I->S=.. ... M->E=.." line per L1 (4 cores), emitted by
Counters.h::summaryString(). The Miranda files also carry the full SST
statistics dump (per-core req_latency, cycles) and "simulated time".

Output: results/TABLES.md  -- summed-over-4-cores tables, MESI vs MSI per
pattern, and base vs opt for the migratory microbenchmark.
"""
import re, os, glob, collections

here = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(here, 'results')

COUNTER_RE = re.compile(r'Counter\[(l1cache\d)\]\s+(.*)')
KV_RE = re.compile(r'([A-Za-z_>\-]+)=(\d+)')

def parse_counters(path):
    """-> {cache: {key: int}} plus 'sim_time' and per-core cycles / latency if present"""
    out = {'caches': {}, 'sim_time': None, 'core_cycles': {}, 'core_lat_sum': {}, 'core_lat_n': {}}
    with open(path) as f:
        for line in f:
            m = COUNTER_RE.search(line)
            if m:
                out['caches'][m.group(1)] = {k: int(v) for k, v in KV_RE.findall(m.group(2))}
                continue
            m = re.search(r'simulated time:\s*([\d.]+)\s*(\w+)', line)
            if m: out['sim_time'] = f'{m.group(1)} {m.group(2)}'
            m = re.search(r'(core\d)\.cycles\s*:.*?Sum\.u64\s*=\s*(\d+)', line)
            if m: out['core_cycles'][m.group(1)] = int(m.group(2))
            m = re.search(r'(core\d)\.req_latency\s*:.*?Sum\.u64\s*=\s*(\d+).*?Count\.u64\s*=\s*(\d+)', line)
            if m:
                out['core_lat_sum'][m.group(1)] = int(m.group(2)); out['core_lat_n'][m.group(1)] = int(m.group(3))
    return out

def total(d, key):
    return sum(c.get(key, 0) for c in d['caches'].values())

KEYS = ['getS_sent', 'getX_sent', 'getSX_sent', 'inv', 'interv', 'trans',
        'I->S', 'I->E', 'I->M', 'S->I', 'S->E', 'S->M', 'E->I', 'E->S', 'E->M', 'M->I', 'M->S', 'M->E']

def md_table(header, rows):
    w = [max(len(str(x)) for x in col) for col in zip(header, *rows)]
    fmt = lambda r: '| ' + ' | '.join(str(c).ljust(w[i]) for i, c in enumerate(r)) + ' |'
    return '\n'.join([fmt(header), '|' + '|'.join('-' * (x + 2) for x in w) + '|'] + [fmt(r) for r in rows])

lines = []
lines.append('# SST results — parsed from the raw counter dumps\n')
lines.append('*Generated by `parse_results.py`. Every number is a sum over the four L1s in one `.out` file; per-cache lines are in `results/`.*\n')

# ---- Part 1: Miranda bus suite, MESI vs MSI -------------------------------
lines.append('## Part 1 — Miranda bus-coherence suite, MESI vs MSI (4 cores)\n')
pats = collections.OrderedDict()
for p in sorted(glob.glob(os.path.join(R, 'miranda', 'miranda_bus_suite_*_*.out'))):
    name = os.path.basename(p)[len('miranda_bus_suite_'):-4]
    pattern, proto = name.rsplit('_', 1)
    pats.setdefault(pattern, {})[proto] = parse_counters(p)

hdr = ['pattern', 'proto', 'GetS', 'GetX', 'inv', 'interv', 'trans', 'S->E', 'E->M', 'S->I', 'M->I', 'M->S', 'sim time']
rows = []
for pattern, d in pats.items():
    for proto in ('msi', 'mesi'):
        if proto not in d: continue
        x = d[proto]
        rows.append([pattern, proto.upper(), total(x, 'getS_sent'), total(x, 'getX_sent'), total(x, 'inv'),
                     total(x, 'interv'), total(x, 'trans'), total(x, 'S->E'), total(x, 'E->M'),
                     total(x, 'S->I'), total(x, 'M->I'), total(x, 'M->S'), x['sim_time'] or ''])
lines.append(md_table(hdr, rows) + '\n')

# what MESI saved, pattern by pattern
lines.append('### What the E state buys, per pattern (MSI − MESI)\n')
hdr2 = ['pattern', 'GetX MSI', 'GetX MESI', 'upgrades removed', 'inv MSI', 'inv MESI', 'note']
rows2 = []
for pattern, d in pats.items():
    if 'msi' in d and 'mesi' in d:
        gx_m, gx_e = total(d['msi'], 'getX_sent'), total(d['mesi'], 'getX_sent')
        iv_m, iv_e = total(d['msi'], 'inv'), total(d['mesi'], 'inv')
        se = total(d['mesi'], 'S->E'); em = total(d['mesi'], 'E->M')
        note = f'S->E={se}, E->M={em}: private lines went I->E and wrote silently' if em else ''
        rows2.append([pattern, gx_m, gx_e, gx_m - gx_e, iv_m, iv_e, note])
lines.append(md_table(hdr2, rows2) + '\n')

# per-core latency where present
lines.append('### Per-core request latency (mean cycles, from SST `req_latency` accumulators)\n')
hdr3 = ['pattern', 'proto', 'core0', 'core1', 'core2', 'core3', 'sim time']
rows3 = []
for pattern, d in pats.items():
    for proto in ('msi', 'mesi'):
        if proto not in d: continue
        x = d[proto]
        cells = []
        for c in ('core0', 'core1', 'core2', 'core3'):
            if c in x['core_lat_sum'] and x['core_lat_n'].get(c):
                cells.append(f"{x['core_lat_sum'][c] / x['core_lat_n'][c]:.1f}")
            else:
                cells.append('')
        rows3.append([pattern, proto.upper()] + cells + [x['sim_time'] or ''])
lines.append(md_table(hdr3, rows3) + '\n')

# ---- Part 2: prospero migratory microbenchmark, base vs opt -----------------
lines.append('## Part 2 — migratory-sharing optimization (read miss → GetX), 4 cores, one read→write pair each\n')
base = parse_counters(os.path.join(R, 'prospero', 'prospero_mesi_base.out'))
opt  = parse_counters(os.path.join(R, 'prospero', 'prospero_mesi_opt.out'))
hdr4 = ['metric', 'base (coherence_opt=0)', 'opt (coherence_opt=1)']
rows4 = []
for k, label in [('getS_sent', 'GetS sent'), ('getX_sent', 'GetX sent'), ('inv', 'invalidations seen'),
                 ('interv', 'interventions'), ('trans', 'recorded transitions'), ('S->I', 'S->I'), ('M->S', 'M->S'), ('M->I', 'M->I'), ('S->M', 'S->M (counter)')]:
    rows4.append([label, total(base, k), total(opt, k)])
rows4.append(['**bus requests (GetS+GetX)**', total(base, 'getS_sent') + total(base, 'getX_sent'), total(opt, 'getS_sent') + total(opt, 'getX_sent')])
lines.append(md_table(hdr4, rows4) + '\n')
lines.append('Note: `S->M` reads 0 in **both** runs. The base upgrade goes S → SM → M through a transient state that '
             '`recordTransition` does not canonicalise, so that counter never fires. The upgrade evidence is `GetX sent` '
             '(one per core in base, for the write after the read) and `S->I` on the other sharers. Do not cite "S->M 0" as a result.\n')
lines.append('Not in these files: cycle counts for base vs opt. `run-prospero-traces.py` filtered stdout to `Counter[` lines only, '
             'so the SST `stateEvent_*` statistics and the simulated time were discarded before the `.out` was written.\n')

with open(os.path.join(R, 'TABLES.md'), 'w') as f:
    f.write('\n'.join(lines))
print('\n'.join(lines))
